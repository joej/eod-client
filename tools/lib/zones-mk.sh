# zones-mk.sh CLIENT MPK ZONES_TSV: writes (to stdout) the Makefile's zone table: every zone in the
# zone table whose data archive is in this install, by kind:
#
#   ZONES += 208          outdoor (a heightmap): converted
#   CITIES += 026         a capital city (city.csv: pieces in city coordinates, no terrain): converted
#   OTHERS += 019         a dungeon, a "skycity" or other: listed, not converted yet (roadmap M11)
#   zone208_NAME := Cursed Forest
#   zone208_KIND := outdoor | city | dungeon | skycity | other
#   zone208_DAT := /path/to/zones/zone208/dat208.mpk
#   zone208_POS := --offset 450560 483328 --size 8 8
#   zone208_EDGES := --edges DAT:X:Y,...   outdoor zones of the region bordering its south or east edge
#   zone208_EDGEDAT := DAT ...              (their archives, so the terrain is redone when one changes)
#
# The Makefile regenerates it when the zone table or this script changes.
set -euo pipefail
client=$1 mpk=$2 tsv=$3
[ -d "$client/zones" ] || { echo "zones-mk.sh: no zones/ folder in '$client'" >&2; exit 1; }

echo "# Generated by tools/lib/zones-mk.sh from $(basename "$tsv") and the install's zone archives."
outdoor=$(mktemp)
trap 'rm -f "$outdoor"' EXIT
grep -v '^#' "$tsv" | while IFS=$'\t' read -r zone region ox oy w h name; do
    [ -n "$zone" ] || continue
    n=$(printf %03d "$zone")
    # Folder and archive names vary in case between installs (Zone000 vs zone001). The tutorial's zones
    # (region 27, zones.dat tutorial=1) load from Tutorial/zones, which the client prefers to the older
    # copy of zone 27 in zones/; zones 28 and 29 exist only there.
    dat=$(find "$client" -maxdepth 4 -ipath "$client/tutorial/zones/zone$n/dat$n.mpk" 2>/dev/null | head -1)
    [ -n "$dat" ] || dat=$(find "$client/zones" -maxdepth 2 -ipath "*/zone$n/dat$n.mpk" | head -1)
    [ -n "$dat" ] || continue
    case "$dat" in *[[:space:]]*) echo "zones-mk.sh: '$dat' has a space (make can't take it)" >&2; exit 1 ;; esac
    members=$("$mpk" list "$dat" 2>/dev/null | tr '[:upper:]' '[:lower:]')
    if grep -q 'terrain\.pcx' <<<"$members"; then kind=outdoor; echo "ZONES += $n"; printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$n" "$region" "$ox" "$oy" "$w" "$h" "$dat" >> "$outdoor"
    elif grep -q 'city\.csv' <<<"$members"; then kind=city; echo "CITIES += $n"
    elif grep -q 'skycity\.' <<<"$members"; then kind=skycity; echo "OTHERS += $n"
    elif grep -q 'dungeon\.' <<<"$members"; then kind=dungeon; echo "OTHERS += $n"
    else kind=other; echo "OTHERS += $n"
    fi
    echo "zone${n}_KIND := $kind"
    echo "zone${n}_NAME := $name"
    echo "zone${n}_DAT := $dat"
    echo "zone${n}_POS := --offset $((ox * 8192)) $((oy * 8192)) --size $w $h"
done
# Each outdoor zone's neighbours on its east and south edges (same region, touching the edge, corners
# included): mpk terrain makes its last column and row meet their ground.
awk -F'\t' '
    { n[NR] = $1; r[NR] = $2; x[NR] = $3; y[NR] = $4; w[NR] = $5; h[NR] = $6; d[NR] = $7 }
    END {
        for (i = 1; i <= NR; i++) {
            edges = ""; dats = ""
            for (j = 1; j <= NR; j++) {
                if (i == j || r[i] != r[j]) continue
                east  = x[j] == x[i] + w[i] && y[j] <= y[i] + h[i] && y[j] + h[j] >= y[i]
                south = y[j] == y[i] + h[i] && x[j] <= x[i] + w[i] && x[j] + w[j] >= x[i]
                if (!east && !south) continue
                edges = edges (edges == "" ? "" : ",") d[j] ":" x[j] * 8192 ":" y[j] * 8192
                dats = dats " " d[j]
            }
            if (edges != "") {
                print "zone" n[i] "_EDGES := --edges " edges
                print "zone" n[i] "_EDGEDAT :=" dats
            }
        }
    }' "$outdoor"
