    // zonedeps <dat<NNN>.mpk> --index index.json --var NAME: the models a zone places, as a make
    // fragment ("NAME := a.nif b.nif"), so the Makefile knows which library targets a zone needs.
    // Models the install doesn't have are listed in a comment, not as targets.
    private static int ZoneDepsCmd(string[] args)
    {
        string datMpk = args[1];
        if (Options.Parse(args, 2, ["--index", "--var"]) is not { } o
            || o["--index"] is not { } indexPath || o["--var"] is not { } var)
            return Usage();
        try
        {
            AssetIndex index = AssetIndex.Load(indexPath);
            IReadOnlyList<string> names = ZoneExport.ModelNames(datMpk, TreeClusters.Load(index.Root));
            var have = names.Where(index.Contains).ToList();
            var bad = have.FirstOrDefault(n => n.Any(c => !(char.IsAsciiLetterOrDigit(c) || c is '_' or '-' or '.')));
            if (bad is not null)
            {
                Console.Error.WriteLine($"zonedeps: model name '{bad}' has characters make can't take as a target");
                return 1;
            }
            Console.WriteLine($"# Generated by mpk zonedeps from {Path.GetFileName(datMpk)}: {have.Count} model(s) in the install.");
            foreach (string missing in names.Where(n => !index.Contains(n)))
                Console.WriteLine($"# not in the install: {missing}");
            Console.WriteLine($"{var} := {string.Join(' ', have)}");
            return 0;
        }
        catch (Exception e) when (e is MpkFormatException or IOException)
        {
            Console.Error.WriteLine($"zonedeps: {e.Message}");
            return 1;
        }
    }

    // The tutorial's zones (region 27, zones.dat `tutorial=1`) load from Tutorial/zones, with their models
    // and textures from Tutorial/zones/nifs first: nine of those differ from the zones/Nifs file of the same
    // name, so they convert into the library's "tutorial" scope (models/tutorial/, textures/tutorial/).
    internal static readonly string[] TutorialFolders = ["Tutorial/zones/"];

    internal static AssetLibrary ZoneLibrary(AssetLibrary library, string datMpk) =>
        Path.GetFullPath(datMpk).Replace('\\', '/').Contains("/tutorial/zones/", StringComparison.OrdinalIgnoreCase)
            ? library.ZoneScoped("tutorial", TutorialFolders) : library;

    private static int ZoneCmd(string[] args)
    {
        // zone <dat<NNN>.mpk> --index index.json --library LIBDIR --offset X Y --out DIR
        if (args.Length < 2)
            return Usage();
        string datMpk = args[1];
        if (Options.Parse(args, 2, ["--out", "--index", "--library", "--size", "--offset"]) is not { } o)
            return Usage();
        string? outDir = o["--out"], indexPath = o["--index"], libDir = o["--library"];
        if (outDir is null || libDir is null || indexPath is null || o.Offset is not var (offX, offY))
        {
            Console.Error.WriteLine("zone: --index index.json, --library LIBDIR, --offset X Y and " +
                "--out DIR are required (offset = the zone's region offsetX/offsetY, i.e. zones.tsv x 8192).");
            return 2;
        }
        if (!File.Exists(datMpk)) { Console.Error.WriteLine($"No such zone archive: {datMpk}"); return 1; }
        if (!File.Exists(indexPath)) { Console.Error.WriteLine($"No such index: {indexPath} (run `mpk index` first)."); return 1; }

        try
        {
            AssetIndex index = AssetIndex.Load(indexPath);
            var library = ZoneLibrary(new AssetLibrary(index, libDir), datMpk);
            ZoneExportReport r = ZoneExport.Export(library, datMpk, offX, offY, outDir, o.ZoneSize.X, o.ZoneSize.Y,
                TreeClusters.Load(index.Root));
            Console.WriteLine($"Zone: {r.Fixtures} fixtures, {r.Models} distinct models -> " +
                $"{r.Converted} in library, {r.MissingModel} not found; " +
                $"{r.Placed} placements ({r.Grounded} stood on the terrain){(r.Doors > 0 ? $", {r.Doors} door(s)" : "")} written to {Path.GetFullPath(outDir)}/zone.csv " +
                $"(library: {Path.GetFullPath(libDir)})");
            foreach (string failure in r.Failures)
                Console.WriteLine($"  FAILED to convert {failure}");
            return r.Failed > 0 ? 1 : 0;
        }
        catch (Exception e) when (e is MpkFormatException or DirectoryNotFoundException or InvalidDataException)
        {
            Console.Error.WriteLine($"zone: {e.Message}");
            return 1;
        }
    }

    private static int TerrainCmd(string[] args)
    {
        // terrain <dat<NNN>.mpk> --offset X Y --out FILE.glb [--tiles N] [--index index.json --library LIBDIR]
        //         [--edges DAT:X:Y,...]  the zones bordering its south and east edges (their archives and
        //                                region offsets), so its last row and column meet their ground
        if (args.Length < 2)
            return Usage();
        string datMpk = args[1];
        if (Options.Parse(args, 2, ["--out", "--index", "--library", "--tiles", "--size", "--offset", "--edges"]) is not { } o)
            return Usage();
        int tiles = 8;  // the painted ground is an 8x8 grid of texRR-CC tiles (verified on the install).
        if (o["--tiles"] is { } tn && !int.TryParse(tn, out tiles))
            return Usage();
        string? outPath = o["--out"], indexPath = o["--index"], libDir = o["--library"];
        if (outPath is null || o.Offset is not var (offX, offY))
        {
            Console.Error.WriteLine("terrain: --offset X Y and --out FILE.glb are required " +
                "(offset = the zone's region offsetX/offsetY, i.e. zones.tsv x 8192).");
            return 2;
        }
        if (!File.Exists(datMpk)) { Console.Error.WriteLine($"No such zone archive: {datMpk}"); return 1; }
        if ((indexPath is null) != (libDir is null))
        {
            Console.Error.WriteLine("terrain: pass --index and --library together to gather the ground tiles.");
            return 2;
        }

        try
        {
            ZoneTerrain terrain = ZoneTerrain.Read(datMpk, o.ZoneSize.X, o.ZoneSize.Y);
            var neighbours = new List<TerrainNeighbour>();
            foreach (string edge in (o["--edges"] ?? "").Split(',', StringSplitOptions.RemoveEmptyEntries))
            {
                string[] f = edge.Split(':');
                if (f.Length != 3 || !int.TryParse(f[1], out int nx) || !int.TryParse(f[2], out int ny) || !File.Exists(f[0]))
                {
                    Console.Error.WriteLine($"terrain: --edges takes DAT:X:Y (an existing zone archive and its region offset): '{edge}'");
                    return 2;
                }
                neighbours.Add(new TerrainNeighbour(ZoneTerrain.Read(f[0]), nx, ny));
            }
            var meshes = terrain.BuildTiledMesh(offX, offY, tiles, neighbours);
            var model = new NifModel { Version = new NifVersion(0, 0, 0, 0), Meshes = [.. meshes] };
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(outPath))!);
            GltfExporter.SaveGlb(model, outPath);

            int verts = 0, tris = 0;
            foreach (NifMesh m in meshes) { verts += m.Vertices.Length; tris += m.Triangles.Length; }
            Console.WriteLine($"Terrain: {terrain.Cells}x{terrain.Cells} heightmap, {meshes.Count} tile(s), " +
                $"{verts} verts, {tris} tris, {neighbours.Count} bordering zone(s) -> {Path.GetFullPath(outPath)}");

            // Gather the ground tiles into the library so the client textures the terrain like any model.
            if (indexPath is not null && libDir is not null)
            {
                if (!File.Exists(indexPath)) { Console.Error.WriteLine($"No such index: {indexPath} (run `mpk index` first)."); return 1; }
                // Each zone's own 64 tiles (the same names in every zone: never looked up by name across zones), from its
                // texNNN.mpk or the use_texture zone's, into textures/terrain/zoneNNN/, where the client looks first.
                string zoneDigits = new(Path.GetFileNameWithoutExtension(datMpk).Where(char.IsDigit).ToArray());
                string tileDir = Path.Combine(libDir, "textures", "terrain", $"zone{zoneDigits}");
                int got = 0, miss = 0;
                if (ZoneTerrain.TileArchive(datMpk, terrain.UseTexture) is string tileMpk)
                {
                    Directory.CreateDirectory(tileDir);
                    using MpkArchive tex = MpkArchive.Open(tileMpk);
                    foreach (NifMesh m in meshes)
                    {
                        // By name across extensions: some zones' tiles are .bmp (zones 100-104 and others), kept as they are
                        // (the client binds a tile by its stem, any of .dds/.tga/.bmp/.png).
                        string stem = Path.GetFileNameWithoutExtension(m.TextureFile ?? "");
                        MpkEntry? e = stem.Length == 0 ? null : new[] { ".dds", ".bmp", ".tga" }
                            .Select(ext => tex.TryGetEntry(stem + ext, out MpkEntry x) ? x : (MpkEntry?)null).FirstOrDefault(x => x is not null);
                        if (e is MpkEntry entry)
                        {
                            byte[] bytes = tex.Extract(entry);
                            // The install's BMP tiles store their file size in 4-byte units (16653 for 66,614 bytes), which
                            // Godot's loader takes as the length and refuses: write the true size.
                            if (bytes.Length > 6 && bytes[0] == 'B' && bytes[1] == 'M')
                                BitConverter.GetBytes(bytes.Length).CopyTo(bytes, 2);
                            File.WriteAllBytes(Path.Combine(tileDir, entry.Name.ToLowerInvariant()), bytes);
                            got++;
                        }
                        else
                            miss++;
                    }
                    Console.WriteLine($"  tiles: {got} from {Path.GetFileName(tileMpk)}, {miss} missing -> {Path.GetFullPath(tileDir)}" +
                                      (terrain.FlipX || terrain.FlipY ? $" (mirrored: {(terrain.FlipX ? "x" : "")}{(terrain.FlipY ? "y" : "")})" : ""));
                }
                else
                    Console.WriteLine($"  tiles: no texNNN.mpk for this zone{(terrain.UseTexture is int u ? $" or zone {u}" : "")}");

                // "Atlantis Terrain" (W8): the zone's layered ground, from its terNNN.mpk: atlantis.csv beside terrain.glb,
                // the masks into the zone's tile folder, the layer textures into textures/terraintex/<folder>/.
                string atlantisCsv = Path.Combine(Path.GetDirectoryName(Path.GetFullPath(outPath))!, "atlantis.csv");
                string? terMpk = Directory.EnumerateFiles(Path.GetDirectoryName(Path.GetFullPath(datMpk))!)
                    .FirstOrDefault(f => Path.GetFileName(f).Equals($"ter{zoneDigits}.mpk", StringComparison.OrdinalIgnoreCase));
                if (terMpk is not null && AtlantisLayers(terMpk, datMpk, tileDir, libDir) is { } layers)
                {
                    // The zone's mirroring too, so the client can undo it for the masks (the tiles' UVs carry it).
                    File.WriteAllText(atlantisCsv, AtlantisTerrain.ToCsv(layers.Layers) + $"flip,{(terrain.FlipX ? 1 : 0)},{(terrain.FlipY ? 1 : 0)}\n");
                    Console.WriteLine($"  atlantis: {layers.Layers.Count} layers on {layers.Layers.Select(l => (l.PatchX, l.PatchY)).Distinct().Count()} patches, " +
                                      $"{layers.Textures} textures, {layers.Masks} masks, {layers.Missing} textures missing");
                }
                else if (File.Exists(atlantisCsv))
                    File.Delete(atlantisCsv);
            }
            return 0;
        }
        catch (Exception e) when (e is MpkFormatException or FormatException)
        {
            Console.Error.WriteLine($"terrain: {e.Message}");
            return 1;
        }
    }

    // The Atlantis layers of a terNNN.mpk, their masks copied into tileDir/atlantis and their textures into
    // textures/terraintex/<scope>/ (the layer's Texture becomes that library path; "" when the install lacks it).
    private static (List<AtlantisLayer> Layers, int Textures, int Masks, int Missing)? AtlantisLayers(
        string terMpk, string datMpk, string tileDir, string libDir)
    {
        using MpkArchive ter = MpkArchive.Open(terMpk);
        if (!ter.TryGetEntry("textures.csv", out MpkEntry csvEntry))
            return null;
        List<AtlantisLayer> layers = AtlantisTerrain.Parse(System.Text.Encoding.Latin1.GetString(ter.Extract(csvEntry)));
        if (layers.Count == 0)
            return null;
        string maskDir = Path.Combine(tileDir, "atlantis");
        Directory.CreateDirectory(maskDir);
        int masks = 0;
        foreach (string mask in layers.Select(l => l.Weight.Mask).Distinct())
            if (ter.TryGetEntry(mask, out MpkEntry m))
            {
                File.WriteAllBytes(Path.Combine(maskDir, mask), ter.Extract(m));
                masks++;
            }
        var folders = AtlantisTerrain.TextureFolders(datMpk);
        var resolved = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        int missing = 0;
        foreach (string name in layers.Select(l => l.Texture).Distinct(StringComparer.OrdinalIgnoreCase))
        {
            string found = "";
            foreach ((string scope, string folder) in folders)
                if (Directory.EnumerateFiles(folder).FirstOrDefault(f =>
                        Path.GetFileName(f).Equals(name + ".dds", StringComparison.OrdinalIgnoreCase)) is string file)
                {
                    found = $"{scope}/{name.ToLowerInvariant()}.dds";
                    string dest = Path.Combine(libDir, "textures", "terraintex", scope, name.ToLowerInvariant() + ".dds");
                    if (!File.Exists(dest) || new FileInfo(dest).Length != new FileInfo(file).Length)
                    {
                        Directory.CreateDirectory(Path.GetDirectoryName(dest)!);
                        DaocAssets.InstallFiles.Copy(file, dest, overwrite: true);
                    }
                    break;
                }
            if (found.Length == 0)
                missing++;
            resolved[name] = found;
        }
        return (layers.Select(l => l with { Texture = resolved[l.Texture] }).ToList(), resolved.Count(r => r.Value.Length > 0), masks, missing);
    }

    // water <dat<NNN>.mpk> --offset X Y --out DIR [--index index.json --library LIBDIR]: the zone's
    // rivers, lakes and swamps (SECTOR.DAT [riverNN]) as DIR/water.glb, one mesh per body named
    // waterNN, plus DIR/water.csv with each body's texture, overlay, flow and type for the client.
    private static int WaterCmd(string[] args)
    {
        if (args.Length < 2)
            return Usage();
        string datMpk = args[1];
        if (Options.Parse(args, 2, ["--out", "--index", "--library", "--size", "--offset"]) is not { } o)
            return Usage();
        string? outDir = o["--out"], indexPath = o["--index"], libDir = o["--library"];
        if (outDir is null || o.Offset is not var (offX, offY) || (indexPath is null) != (libDir is null))
            return Usage();
        if (!File.Exists(datMpk)) { Console.Error.WriteLine($"No such zone archive: {datMpk}"); return 1; }

        // SECTOR.DAT as the client reads it: the csv archive's copy first (its water types and rivers differ in 43 zones).
        using DaocAssets.Zone.ZoneArchive zone = DaocAssets.Zone.ZoneArchive.Open(datMpk);
        // A dungeon's water is its dungeon.water planes, not SECTOR.DAT's rivers (DungeonWater).
        if (DaocAssets.Zone.DungeonLayout.IsDungeon(zone.Dat))
            return DungeonWaterOut(zone, outDir, indexPath, libDir);
        if (zone.Text("SECTOR.DAT") is not string sectorText)
        {
            Console.Error.WriteLine("water: no SECTOR.DAT in this archive.");
            return 1;
        }
        var bodies = ZoneWater.Parse(sectorText, o.ZoneSize.X);
        Directory.CreateDirectory(outDir);
        File.WriteAllLines(Path.Combine(outDir, "water.csv"),
            [ZoneWater.CsvHeader, .. bodies.Select(ZoneWater.CsvRow)]);
        if (bodies.Count == 0)
        {
            Console.WriteLine($"No water in this zone -> {Path.GetFullPath(Path.Combine(outDir, "water.csv"))} (header only)");
            return 0;
        }
        var meshes = bodies.Select(b => ZoneWater.BuildMesh(b, offX, offY)).ToList();
        string glb = Path.Combine(outDir, "water.glb");
        GltfExporter.SaveGlb(new NifModel { Version = new NifVersion(0, 0, 0, 0), Meshes = meshes }, glb);
        foreach (WaterBody b in bodies)
            Console.WriteLine($"  {b.MeshName}: {b.Type,-6} \"{b.Name}\" height {b.Height}, {Math.Min(b.Left.Count, b.Right.Count)} bank pairs, " +
                $"texture {b.Texture}{(b.MultiTexture.Length > 0 ? "+" + b.MultiTexture : "")}, flow {b.Flow}");
        Console.WriteLine($"Water: {bodies.Count} bod{(bodies.Count == 1 ? "y" : "ies")} -> {Path.GetFullPath(glb)}");

        if (indexPath is not null && libDir is not null)
        {
            var library = new AssetLibrary(AssetIndex.Load(indexPath), libDir);
            foreach (string stem in bodies.SelectMany(b => new[] { b.Texture, b.MultiTexture }).Where(t => t.Length > 0).Distinct())
                Console.WriteLine($"  texture {stem}: " + (library.GatherTexture(stem + ".dds") is not null ? "gathered" : "MISSING"));
        }
        return 0;
    }

    // A dungeon's water planes as water.csv + water.glb, the outdoor water's files (the client draws both alike).
    private static int DungeonWaterOut(DaocAssets.Zone.ZoneArchive zone, string outDir, string? indexPath, string? libDir)
    {
        var planes = DaocAssets.Zone.DungeonWater.Parse(DatText(zone.Dat, "dungeon.water"));
        var rooms = DaocAssets.Zone.DungeonWater.ParseRooms(DatText(zone.Dat, "dungeon.water.csv"));
        Directory.CreateDirectory(outDir);
        File.WriteAllLines(Path.Combine(outDir, "water.csv"),
            [ZoneWater.CsvHeader, .. planes.Select(p => DaocAssets.Zone.DungeonWater.CsvRow(p, rooms.GetValueOrDefault(p.Id) ?? []))]);
        string glb = Path.Combine(outDir, "water.glb");
        if (planes.Count == 0)
        {
            if (File.Exists(glb))
                File.Delete(glb);
            Console.WriteLine($"No water in this dungeon -> {Path.GetFullPath(Path.Combine(outDir, "water.csv"))} (header only)");
            return 0;
        }
        GltfExporter.SaveGlb(new NifModel { Version = new NifVersion(0, 0, 0, 0), Meshes = planes.Select(DaocAssets.Zone.DungeonWater.BuildMesh).ToList() }, glb);
        foreach (var p in planes)
            Console.WriteLine($"  {p.MeshName}: {p.Kind,-5} height {p.Height:0}, rooms {string.Join(' ', rooms.GetValueOrDefault(p.Id) ?? [])}");
        Console.WriteLine($"Water: {planes.Count} plane(s) -> {Path.GetFullPath(glb)}");
        if (indexPath is not null && libDir is not null)
        {
            var library = new AssetLibrary(AssetIndex.Load(indexPath), libDir);
            foreach (string stem in planes.Select(p => p.Type == 6 ? ZoneWater.DefaultLavaTexture : ZoneWater.DefaultTexture).Distinct())
                Console.WriteLine($"  texture {stem}: " + (library.GatherTexture(stem + ".dds") is not null ? "gathered" : "MISSING"));
        }
        return 0;
    }

    private static string DatText(DaocAssets.Mpk.MpkArchive dat, string name) =>
        dat.TryGetEntry(name, out var e) ? System.Text.Encoding.Latin1.GetString(dat.Extract(e)) : "";

    // zonecheck <dat<NNN>.mpk> --zone DIR --library LIBDIR --offset X Y [--out FILE.md]: places every
    // object of a converted zone (DIR/zone.csv) as the client does and checks it against the terrain:
    // missing models, objects under the ground, sunk, floating, outside the zone, implausible sizes.
    // Exit code 1 when there are errors, so scripts can stop on them.
    private static int ZoneCheckCmd(string[] args)
    {
        if (args.Length < 2) return Usage();
        string datMpk = args[1];
        if (Options.Parse(args, 2, ["--zone", "--known", "--library", "--out", "--size", "--offset"]) is not { } o
            || o["--zone"] is not { } zoneDir || o["--library"] is not { } libDir || o.Offset is not var (offX, offY))
            return Usage();
        string? outPath = o["--out"], knownPath = o["--known"];
        (int X, int Y) zoneSize = o.ZoneSize;

        // A capital city or a dungeon has no terrain (it is all models): checked without ground.
        DaocAssets.Zone.ZoneTerrain? terrain;
        using (var dat = DaocAssets.Mpk.MpkArchive.Open(datMpk))
            terrain = DaocAssets.Zone.ZoneLayout.IsCity(dat) || DaocAssets.Zone.DungeonLayout.IsDungeon(dat)
                ? null : DaocAssets.Zone.ZoneTerrain.Read(datMpk, zoneSize.X, zoneSize.Y);
        var placements = DaocAssets.Zone.ZoneCheck.ReadManifest(DaocAssets.InstallFiles.ReadAllText(Path.Combine(zoneDir, "zone.csv")));
        var cache = new Dictionary<string, DaocAssets.Zone.ModelBounds?>(StringComparer.OrdinalIgnoreCase);
        // Every texture the library holds, by stem (the client binds a material's texture by its name, in any folder).
        var textureStems = new HashSet<string>(new[] { Path.Combine(libDir, "textures"), Path.Combine(libDir, "overrides") }
            .Where(Directory.Exists).SelectMany(d => Directory.EnumerateFiles(d, "*", SearchOption.AllDirectories))
            .Select(f => Path.GetFileNameWithoutExtension(f)), StringComparer.OrdinalIgnoreCase);
        string ModelPath(string glb) =>
            new[] { Path.Combine(libDir, "overrides", glb), Path.Combine(libDir, "models", glb), Path.Combine(libDir, glb) }
                .FirstOrDefault(File.Exists) ?? "";
        DaocAssets.Zone.ModelBounds? Bounds(string glb)
        {
            if (cache.TryGetValue(glb, out var b)) return b;
            string path = ModelPath(glb);
            return cache[glb] = path.Length == 0 ? null : DaocAssets.Zone.ZoneCheck.GlbBounds(path, textureStems.Contains);
        }
        // A model of particles only (smoke, mist; NifParticleJson beside its glb) has no geometry to check.
        bool ParticlesOnly(string glb) => ModelPath(glb) is { Length: > 0 } path && File.Exists(DaocAssets.Nif.NifParticleJson.PathFor(path));
        var report = DaocAssets.Zone.ZoneCheck.Check(placements,
            terrain is null ? null : (x, y) => terrain.HeightAt(x - offX, y - offY), Bounds,
            offX, offY, zoneSize.X * 8192, zoneSize.Y * 8192, ParticlesOnly);
        if (knownPath is not null)
            report = DaocAssets.Zone.ZoneCheck.ApplyKnown(report, DaocAssets.Zone.ZoneCheck.ReadKnown(DaocAssets.InstallFiles.ReadAllText(knownPath)));
        Console.WriteLine($"Zone check: {report.Summary()}");
        if (outPath is not null)
        {
            File.WriteAllText(outPath, report.ToMarkdown($"Zone check: {Path.GetFileName(Path.GetFullPath(zoneDir))}"));
            Console.WriteLine($"  report -> {Path.GetFullPath(outPath)}");
        }
        return report.Errors > 0 ? 1 : 0;
    }

    // mpk dungeoncheck <dat<NNN>.mpk> --index INDEX [--out FILE.md]: places the dungeon's rooms (DungeonLayout) and
    // measures how far apart the two doorways of each portals.csv link land (DungeonCheck).
    private static int DungeonCheckCmd(string[] args)
    {
        if (args.Length < 2) return Usage();
        string datMpk = args[1];
        if (Options.Parse(args, 2, ["--index", "--out", "--points", "--landing"]) is not { } o || o["--index"] is not { } indexPath)
            return Usage();
        var index = AssetIndex.Load(indexPath);
        DaocAssets.Zone.DungeonLayout layout;
        string portalsCsv;
        List<DaocAssets.Zone.DungeonWaterPlane> planes;
        Dictionary<int, List<int>> planeRooms;
        using (var dat = DaocAssets.Mpk.MpkArchive.Open(datMpk))
        {
            planes = DaocAssets.Zone.DungeonWater.Parse(DatText(dat, "dungeon.water"));
            planeRooms = DaocAssets.Zone.DungeonWater.ParseRooms(DatText(dat, "dungeon.water.csv"));
            if (!DaocAssets.Zone.DungeonLayout.IsDungeon(dat))
            {
                Console.Error.WriteLine($"{datMpk}: not a dungeon (no dungeon.chunk / dungeon.place)");
                return 2;
            }
            layout = DaocAssets.Zone.DungeonLayout.Read(dat);
            portalsCsv = dat.TryGetEntry("portals.csv", out var e) ? System.Text.Encoding.Latin1.GetString(dat.Extract(e)) : "";
        }
        ModelProxy proxy = ModelProxy.FromZoneArchive(datMpk);
        var models = new Dictionary<string, DaocAssets.Nif.NifModel?>(StringComparer.OrdinalIgnoreCase);
        DaocAssets.Nif.NifModel? Model(string piece)
        {
            if (models.TryGetValue(piece, out var found)) return found;
            // Opened as the client opens a piece: zones/Dnifs, then zones/Nifs, with its patch files.
            string name = proxy.Apply(piece);
            byte[]? bytes = index.Read(name, AssetLibrary.DungeonModelFolders);
            DaocAssets.Nif.NifModel? model = null;
            if (bytes is not null)
            {
                try { model = DaocAssets.Nif.NifFile.Read(bytes, index.ReadPatches(name, AssetLibrary.DungeonModelFolders)); }
                catch (Exception ex) when (ex is DaocAssets.Nif.NifFormatException or InvalidDataException or IndexOutOfRangeException) { }
            }
            return models[piece] = model;
        }
        IReadOnlyDictionary<string, System.Numerics.Vector3>? Portals(string piece) =>
            Model(piece) is { } m ? DaocAssets.Zone.DungeonCheck.PortalNodes(m.NodeWorlds) : null;
        var links = DaocAssets.Zone.DungeonCheck.Check(layout, DaocAssets.Zone.DungeonCheck.ParsePortals(portalsCsv), Portals);
        var measured = links.Where(l => l.Gap is not null).Select(l => l.Gap!.Value).OrderBy(g => g).ToList();
        int met = measured.Count(g => g <= 2), near = measured.Count(g => g > 2 && g <= 64);
        string summary = $"{layout.Rooms.Count} rooms, {layout.Props.Count} props, {links.Count} portal links: " +
            $"{met} meet (<= 2 units), {near} within 64, {measured.Count - met - near} apart, {links.Count - measured.Count} unmeasured" +
            (measured.Count > 0 ? $"; median {measured[measured.Count / 2]:0.#}, max {measured[^1]:0.#}" : "") +
            (layout.Skipped.Count > 0 ? $"; {layout.Skipped.Count} row(s) skipped" : "");
        // Water: each plane against its rooms' water height (dungeon.place column 10) and the floors under it.
        IReadOnlyList<(System.Numerics.Vector3, System.Numerics.Vector3, System.Numerics.Vector3)>? Surfaces(string piece) =>
            Model(piece) is { } m
                ? m.Meshes.Where(x => !x.Helper || x.Collision)
                    .SelectMany(x => x.Triangles.Select(t => (x.Vertices[t.A], x.Vertices[t.B], x.Vertices[t.C]))).ToList()
                : null;
        var waterLines = new List<string>();
        foreach (var p in planes)
        {
            var heights = (planeRooms.GetValueOrDefault(p.Id) ?? [])
                .Select(r => layout.Rooms.FirstOrDefault(x => x.Id == r)).Where(r => r.WaterHeight != 0).Select(r => r.WaterHeight).ToList();
            var grid = DaocAssets.Zone.DungeonWater.RegionGrid(p);
            (int wet, int all) = DaocAssets.Zone.DungeonCheck.Floors(layout,
                grid.ToList(), Surfaces, below: 3000, above: 0);
            waterLines.Add($"{p.MeshName} ({p.Kind}) at {p.Height:0}: rooms' water height " +
                (heights.Count == 0 ? "none given" : $"{heights.Min():0}..{heights.Max():0}") + $"; a floor under {wet} of {all} grid points");
        }
        if (planes.Count > 0)
            summary += $"; water: {planes.Count} plane(s)";

        // --points FILE: "x,y,z" rows in region coordinates (the server's NPCs): how many stand on a floor.
        if (o["--points"] is { } pointsPath)
        {
            var points = File.ReadAllLines(pointsPath).Select(l => l.Split([',', '\t'])).Where(c => c.Length >= 3)
                .Select(c => new System.Numerics.Vector3(float.Parse(c[0], CultureInfo.InvariantCulture),
                    float.Parse(c[1], CultureInfo.InvariantCulture), float.Parse(c[2], CultureInfo.InvariantCulture))).ToList();
            (int on, int all) = DaocAssets.Zone.DungeonCheck.Floors(layout, points, piece => Model(piece) is { } m
                ? m.Meshes.Where(x => !x.Helper || x.Collision)
                    .SelectMany(x => x.Triangles.Select(t => (x.Vertices[t.A], x.Vertices[t.B], x.Vertices[t.C]))).ToList()
                : null);
            summary += $"; {on} of {all} points stand on a floor";
        }
        // --landing FILE: the zone's landing spot ("x y z", region), written by `mpk zone` from the exit doorway, checked
        // against the rooms' floors and moved onto the nearest one when it has none (18 dungeons' doorways don't sit on a
        // floor of the assembled rooms; 24 have no doorway). DungeonCheck.Landing.
        if (o["--landing"] is { } landingPath)
        {
            System.Numerics.Vector3? doorway = null;
            if (File.Exists(landingPath) && File.ReadAllText(landingPath).Split(' ', StringSplitOptions.RemoveEmptyEntries) is [var lx, var ly, var lz, ..])
                doorway = new System.Numerics.Vector3(float.Parse(lx, CultureInfo.InvariantCulture), float.Parse(ly, CultureInfo.InvariantCulture),
                    float.Parse(lz, CultureInfo.InvariantCulture));
            // The zone's jump points (jumps.csv beside landing.txt, written by `mpk zone`): a landing keeps clear of them.
            string jumpsPath = Path.Combine(Path.GetDirectoryName(Path.GetFullPath(landingPath))!, "jumps.csv");
            var doorways = File.Exists(jumpsPath)
                ? File.ReadAllLines(jumpsPath).Skip(1).Select(l => l.Split(',')).Where(c => c.Length >= 8)
                    .Select(c => c[2..8].Select(v => float.Parse(v, CultureInfo.InvariantCulture)).ToArray())
                    .Select(v => new DaocAssets.Zone.DungeonCheck.Doorway(new(v[0], v[1]), new(v[2], v[3]), v[4], v[5])).ToList()
                : [];
            if (DaocAssets.Zone.DungeonCheck.Landing(layout, doorway, Surfaces, doorways) is { } spot)
            {
                File.WriteAllText(landingPath, string.Create(CultureInfo.InvariantCulture, $"{spot.X:0} {spot.Y:0} {spot.Z:0}\n"));
                summary += spot == doorway ? "; landing on a floor" : $"; landing moved to a floor at ({spot.X:0}, {spot.Y:0}, {spot.Z:0})";
            }
            else
                summary += "; no floor for a landing";
        }
        Console.WriteLine($"Dungeon check: {summary}");
        foreach (string w in waterLines)
            Console.WriteLine($"  water: {w}");
        if (o["--out"] is { } outPath)
        {
            var sb = new System.Text.StringBuilder($"# Dungeon check: {Path.GetFileName(datMpk)}\n\n{summary}\n\n");
            foreach (var l in links.Where(l => l.Gap is null or > 2).OrderByDescending(l => l.Gap ?? float.MaxValue))
                sb.Append($"- room {l.RoomA} ({layout.Rooms.FirstOrDefault(r => r.Id == l.RoomA).Piece}) portal{l.Portal:00} -> room {l.RoomB}: " +
                    (l.Gap is float g ? $"{g:0.#} units apart\n" : "not measured\n"));
            foreach (string s in layout.Skipped)
                sb.Append($"- skipped: {s}\n");
            foreach (string w in waterLines)
                sb.Append($"- water: {w}\n");
            File.WriteAllText(outPath, sb.ToString());
        }
        return 0;
    }
